package features

import (
	"fmt"
	"sort"
	"strings"

	"github.com/griffithind/dcx/internal/shell"
)

// DockerfileGenerator generates Dockerfiles for feature installation.
type DockerfileGenerator struct {
	baseImage         string
	features          []*Feature
	buildDir          string
	remoteUser        string
	remoteUserHome    string
	containerUser     string
	containerUserHome string
	metadata          string
	imageUser         string
}

// FeatureUsers applies the spec's defaults to the users features install
// for: the container user defaults to root, the remote user to the
// container user.
func FeatureUsers(remoteUser, containerUser string) (remote, container string) {
	if containerUser == "" {
		containerUser = "root"
	}
	if remoteUser == "" {
		remoteUser = containerUser
	}
	return remoteUser, containerUser
}

// NewDockerfileGenerator creates a new Dockerfile generator for the
// configured remoteUser and containerUser (see FeatureUsers for defaults).
func NewDockerfileGenerator(baseImage string, features []*Feature, buildDir, remoteUser, containerUser string) *DockerfileGenerator {
	remoteUser, containerUser = FeatureUsers(remoteUser, containerUser)
	// The ARG homes are defaults only: builtin.env (BuiltinEnv), sourced
	// by every feature's RUN step, resolves the real ones.
	return &DockerfileGenerator{
		baseImage:         baseImage,
		features:          features,
		buildDir:          buildDir,
		remoteUser:        remoteUser,
		remoteUserHome:    DefaultHomeDir(remoteUser),
		containerUser:     containerUser,
		containerUserHome: DefaultHomeDir(containerUser),
	}
}

// BuiltinEnv is the builtin.env every feature's install step sources. It
// sets _REMOTE_USER/_CONTAINER_USER and resolves their homes when the step
// runs, from the passwd database (so a user an earlier feature created, or
// one with a home outside /home, gets its real home), falling back to the
// conventional /home/<user> or /root.
func BuiltinEnv(remoteUser, containerUser string) string {
	remoteUser, containerUser = FeatureUsers(remoteUser, containerUser)
	return fmt.Sprintf(`#!/bin/sh
# Builtin environment for devcontainer features
# Generated by dcx

_dcx_home() {
	_dcx_h=$( (getent passwd "$1" || grep "^$1:" /etc/passwd) 2>/dev/null | head -n 1 | cut -d: -f6)
	echo "${_dcx_h:-$2}"
}
export _CONTAINER_USER=%[1]s
export _CONTAINER_USER_HOME="$(_dcx_home %[1]s %[2]s)"
export _REMOTE_USER=%[3]s
export _REMOTE_USER_HOME="$(_dcx_home %[3]s %[4]s)"
unset -f _dcx_home
`, shell.Quote(containerUser), shell.Quote(DefaultHomeDir(containerUser)), shell.Quote(remoteUser), shell.Quote(DefaultHomeDir(remoteUser)))
}

// SetImageUser records the base image's USER, restored after the features
// install (they install as root). "" or "root" leaves root in place.
func (g *DockerfileGenerator) SetImageUser(user string) {
	g.imageUser = strings.NewReplacer("\r", "", "\n", "").Replace(user)
}

// SetMetadata sets the devcontainer.metadata label to embed in the image.
func (g *DockerfileGenerator) SetMetadata(metadata string) {
	g.metadata = metadata
}

// Generate creates the Dockerfile content.
// Uses BuildKit build contexts with RUN --mount for efficient feature installation.
func (g *DockerfileGenerator) Generate() string {
	var sb strings.Builder

	// No "# syntax=" directive: BuildKit's built-in Dockerfile frontend
	// supports RUN --mount, and pinning a frontend image made every build
	// depend on pulling it from Docker Hub.
	sb.WriteString("# Generated by dcx - do not edit\n")
	sb.WriteString("# This Dockerfile installs devcontainer features using BuildKit build contexts\n\n")

	// Start from base image. Features install as root (they run package
	// managers), whatever the base image's USER is.
	fmt.Fprintf(&sb, "FROM %s\n\n", g.baseImage)
	sb.WriteString("USER root\n\n")

	// Build-time arguments for feature installation per the spec. The homes
	// are defaults; builtin.env resolves the real ones in each RUN step.
	sb.WriteString("# Feature installation environment\n")
	fmt.Fprintf(&sb, "ARG _REMOTE_USER=%s\n", g.remoteUser)
	fmt.Fprintf(&sb, "ARG _REMOTE_USER_HOME=%s\n", g.remoteUserHome)
	fmt.Fprintf(&sb, "ARG _CONTAINER_USER=%s\n", g.containerUser)
	fmt.Fprintf(&sb, "ARG _CONTAINER_USER_HOME=%s\n\n", g.containerUserHome)

	// Create features temp directory and copy builtin.env from build context
	sb.WriteString("# Setup features directory and copy environment file\n")
	sb.WriteString("RUN mkdir -p /tmp/dcx-features\n")
	sb.WriteString("COPY --from=dev_containers_feature_content_source builtin.env /tmp/dcx-features/\n\n")

	// Install each feature using RUN --mount. A feature's containerEnv is
	// set right after it installs, so later features (which may depend on
	// it, e.g. a PATH entry) see it, as the spec requires.
	for i, feature := range g.features {
		g.generateFeatureInstall(&sb, feature, i)
		g.generateFeatureEnv(&sb, feature)
	}

	// Back to the base image's user, so the derived image runs as before.
	if g.imageUser != "" && g.imageUser != "root" {
		fmt.Fprintf(&sb, "USER %s\n\n", g.imageUser)
	}

	// Add devcontainer.metadata label per spec
	if g.metadata != "" {
		sb.WriteString("# Devcontainer metadata (per spec)\n")
		fmt.Fprintf(&sb, "LABEL devcontainer.metadata=%s\n\n", dockerfileLabelQuote(g.metadata))
	}

	return sb.String()
}

// generateFeatureInstall generates the installation commands for a single feature.
// Uses RUN --mount to efficiently mount feature content from build context,
// following the devcontainer reference implementation pattern.
func (g *DockerfileGenerator) generateFeatureInstall(sb *strings.Builder, feature *Feature, index int) {
	featureName := feature.ID
	featureID := ""
	featureVersion := ""
	featureDescription := ""

	if feature.Metadata != nil {
		if feature.Metadata.Name != "" {
			featureName = feature.Metadata.Name
		}
		featureID = feature.Metadata.ID
		featureVersion = feature.Metadata.Version
		featureDescription = feature.Metadata.Description
	}

	fmt.Fprintf(sb, "# Feature %d: %s\n", index+1, featureName)

	featureDir := fmt.Sprintf("feature_%d", index)

	// Set option environment variables as build args (not persisted in image)
	envVars := feature.EnvVars()
	for _, key := range sortedKeys(envVars) {
		fmt.Fprintf(sb, "ARG %s=%s\n", key, dockerfileQuote(envVars[key]))
	}

	// Quote banner lines for the shell. Newlines are flattened first: even a
	// quoted newline would terminate the Dockerfile RUN instruction.
	echoLine := func(text string) string {
		return "echo " + shell.Quote(strings.NewReplacer("\r", " ", "\n", " ").Replace(text))
	}

	// Use RUN --mount to bind mount feature content from build context
	// This is more efficient than COPY as content is not persisted in the layer
	fmt.Fprintf(sb, "RUN --mount=type=bind,from=dev_containers_feature_content_source,source=%s,target=/tmp/build-features-src/%s \\\n", featureDir, featureDir)
	fmt.Fprintf(sb, "    cp -ar /tmp/build-features-src/%s /tmp/dcx-features/%s && \\\n", featureDir, featureDir)
	fmt.Fprintf(sb, "    chmod -R 0755 /tmp/dcx-features/%s && \\\n", featureDir)
	fmt.Fprintf(sb, "    cd /tmp/dcx-features/%s && \\\n", featureDir)
	sb.WriteString("    set -a && . /tmp/dcx-features/builtin.env && set +a && \\\n")
	sb.WriteString("    if [ -f ./devcontainer-features.env ]; then . ./devcontainer-features.env; fi && \\\n")
	sb.WriteString("    echo '===========================================================================' && \\\n")
	fmt.Fprintf(sb, "    %s && \\\n", echoLine("Feature       : "+featureName))
	fmt.Fprintf(sb, "    %s && \\\n", echoLine("Description   : "+featureDescription))
	fmt.Fprintf(sb, "    %s && \\\n", echoLine("Id            : "+featureID))
	fmt.Fprintf(sb, "    %s && \\\n", echoLine("Version       : "+featureVersion))
	sb.WriteString("    echo '===========================================================================' && \\\n")
	sb.WriteString("    chmod +x ./install.sh && \\\n")
	fmt.Fprintf(sb, "    (./install.sh || { %s; exit 1; }) && \\\n",
		echoLine(fmt.Sprintf("ERROR: Feature \"%s\" (%s) failed to install!", featureName, featureID)))
	fmt.Fprintf(sb, "    rm -rf /tmp/dcx-features/%s\n\n", featureDir)
}

// generateFeatureEnv emits ENV lines for a feature's containerEnv, in a
// stable order so identical inputs produce an identical Dockerfile (and hit
// BuildKit's cache).
func (g *DockerfileGenerator) generateFeatureEnv(sb *strings.Builder, feature *Feature) {
	if feature.Metadata == nil || len(feature.Metadata.ContainerEnv) == 0 {
		return
	}
	for _, key := range sortedKeys(feature.Metadata.ContainerEnv) {
		fmt.Fprintf(sb, "ENV %s=%s\n", key, dockerfileEnvQuote(feature.Metadata.ContainerEnv[key]))
	}
	sb.WriteString("\n")
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// ElevatedFeatures names the features that need elevated permissions
// ("Docker in Docker (privileged)", "Go (capabilities)") for the warning
// dcx prints. Their requirements are merged into the resolved
// configuration by the devcontainer builder.
func ElevatedFeatures(feats []*Feature) []string {
	var names []string
	for _, f := range feats {
		m := f.Metadata
		if m == nil {
			continue
		}
		name := m.Name
		if name == "" {
			name = m.ID
		}
		switch {
		case m.Privileged:
			names = append(names, name+" (privileged)")
		case len(m.CapAdd) > 0:
			names = append(names, name+" (capabilities)")
		}
	}
	return names
}

// dockerfileEnvQuote quotes a feature containerEnv value for a Dockerfile
// ENV instruction. Per the feature spec, ${VAR} references (typically
// "${PATH}") must expand against the image environment, so $ is left
// unescaped; only \ and " are escaped inside the double quotes.
func dockerfileEnvQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// dockerfileQuote quotes a literal value (feature option) for a Dockerfile
// ARG instruction, escaping \, ", $ and ` inside double quotes so nothing
// is expanded.
func dockerfileQuote(s string) string {
	if !strings.ContainsAny(s, " \t\n\"'$`\\!") {
		return s
	}
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, `$`, `\$`)
	s = strings.ReplaceAll(s, "`", "\\`")
	return `"` + s + `"`
}

// dockerfileLabelQuote quotes a value for a Dockerfile LABEL instruction.
// Per the devcontainer reference implementation only ", \ and $ are escaped.
func dockerfileLabelQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, `$`, `\$`)
	return `"` + s + `"`
}

// DefaultHomeDir returns the conventional home directory of a user: /root
// for root, /home/<user> otherwise (_REMOTE_USER_HOME and friends).
func DefaultHomeDir(user string) string {
	if user == "" || user == "root" {
		return "/root"
	}
	return "/home/" + user
}
