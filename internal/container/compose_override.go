package container

import (
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

// composeOverride renders a ContainerSpec as a compose override file for
// service. buildSecrets (secret ID → file) are attached to the service
// build, for compose builds that run without dcx's own image layers.
//
// Every string comes from an already-substituted configuration, so `$` is
// escaped: compose would otherwise interpolate it a second time.
//
// Name is not rendered (compose names its containers); RunArgs have no
// compose equivalent.
func composeOverride(service string, s ContainerSpec, buildSecrets map[string]string) ([]byte, error) {
	return marshalOverride(overrideFile(service, s, buildSecrets))
}

// marshalOverride renders an override file as YAML.
func marshalOverride(file composeFile) ([]byte, error) {
	out, err := yaml.Marshal(file)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by dcx - do not edit\n"), out...), nil
}

// overrideFile builds the override for service (see composeOverride).
func overrideFile(service string, s ContainerSpec, buildSecrets map[string]string) composeFile {
	svc := composeService{
		Image:       esc(s.Image),
		User:        esc(s.User),
		Labels:      escMap(s.Labels),
		Environment: escMap(s.Env),
		CapAdd:      escSlice(s.CapAdd),
		CapDrop:     escSlice(s.CapDrop),
		SecurityOpt: escSlice(s.SecurityOpt),
		Privileged:  s.Privileged,
		NetworkMode: esc(s.NetworkMode),
		Ipc:         esc(s.IpcMode),
		Pid:         esc(s.PidMode),
		ShmSize:     s.ShmSize,
		Devices:     escSlice(s.Devices),
		ExtraHosts:  escSlice(s.ExtraHosts),
		Sysctls:     escMap(s.Sysctls),
		Entrypoint:  escSlice(s.Entrypoint),
		Command:     escSlice(s.Cmd),
	}
	if s.Init {
		init := true
		svc.Init = &init
	}

	for _, path := range sortedKeys(s.Tmpfs) {
		entry := path
		if opts := s.Tmpfs[path]; opts != "" {
			entry += ":" + opts
		}
		svc.Tmpfs = append(svc.Tmpfs, esc(entry))
	}
	for _, p := range s.Ports {
		svc.Ports = append(svc.Ports, p.DockerSpec())
	}

	var volumes map[string]composeTopVolume
	for _, m := range s.Mounts {
		v := composeVolume{
			Type:     m.Type,
			Source:   esc(m.Source),
			Target:   esc(m.Target),
			ReadOnly: m.ReadOnly,
		}
		if v.Type == "" {
			v.Type = "bind"
		}
		if m.Consistency != "" {
			v.Consistency = m.Consistency
		}
		if p := m.Option("bind-propagation"); p != "" || m.Relabel {
			v.Bind = &composeBindOptions{Propagation: p}
			if m.Relabel {
				v.Bind.SELinux = "z"
			}
		}
		if sub, nocopy := m.Option("volume-subpath"), m.Option("volume-nocopy"); sub != "" || nocopy != "" {
			v.Volume = &composeVolumeOptions{Subpath: esc(sub), NoCopy: nocopy == "true" || nocopy == "1"}
		}
		svc.Volumes = append(svc.Volumes, v)

		// Compose rejects named volumes that are not declared, and would
		// prefix undeclared names with the project. Declaring them with an
		// explicit name gives the same volume `docker run --mount` uses.
		if v.Type == "volume" && m.Source != "" {
			if volumes == nil {
				volumes = map[string]composeTopVolume{}
			}
			volumes[esc(m.Source)] = composeTopVolume{Name: esc(m.Source)}
		}
	}

	if s.GPUs != "" {
		dev := composeDevice{Driver: "nvidia", Capabilities: []string{"gpu"}}
		if n, err := strconv.Atoi(s.GPUs); err == nil {
			dev.Count = n
		} else {
			dev.Count = s.GPUs // "all"
		}
		svc.Deploy = &composeDeploy{Resources: composeResources{
			Reservations: composeReservations{Devices: []composeDevice{dev}},
		}}
	}

	file := composeFile{
		Services: map[string]composeService{service: svc},
		Volumes:  volumes,
	}
	if len(buildSecrets) > 0 {
		file.Secrets = map[string]composeSecret{}
		build := &composeBuild{}
		for _, id := range sortedKeys(buildSecrets) {
			build.Secrets = append(build.Secrets, id)
			file.Secrets[id] = composeSecret{File: buildSecrets[id]}
		}
		svc.Build = build
		file.Services[service] = svc
	}
	return file
}

type composeFile struct {
	Services map[string]composeService   `yaml:"services"`
	Volumes  map[string]composeTopVolume `yaml:"volumes,omitempty"`
	Secrets  map[string]composeSecret    `yaml:"secrets,omitempty"`
}

type composeService struct {
	Image       string            `yaml:"image,omitempty"`
	Build       *composeBuild     `yaml:"build,omitempty"`
	User        string            `yaml:"user,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Environment map[string]string `yaml:"environment,omitempty"`
	Volumes     []composeVolume   `yaml:"volumes,omitempty"`
	Tmpfs       []string          `yaml:"tmpfs,omitempty"`
	Ports       []string          `yaml:"ports,omitempty"`
	CapAdd      []string          `yaml:"cap_add,omitempty"`
	CapDrop     []string          `yaml:"cap_drop,omitempty"`
	SecurityOpt []string          `yaml:"security_opt,omitempty"`
	Privileged  bool              `yaml:"privileged,omitempty"`
	Init        *bool             `yaml:"init,omitempty"`
	NetworkMode string            `yaml:"network_mode,omitempty"`
	Ipc         string            `yaml:"ipc,omitempty"`
	Pid         string            `yaml:"pid,omitempty"`
	ShmSize     int64             `yaml:"shm_size,omitempty"`
	Devices     []string          `yaml:"devices,omitempty"`
	ExtraHosts  []string          `yaml:"extra_hosts,omitempty"`
	Sysctls     map[string]string `yaml:"sysctls,omitempty"`
	Deploy      *composeDeploy    `yaml:"deploy,omitempty"`
	Entrypoint  []string          `yaml:"entrypoint,omitempty"`
	Command     []string          `yaml:"command,omitempty"`
}

type composeBuild struct {
	Secrets []string `yaml:"secrets,omitempty"`
}

type composeVolume struct {
	Type        string                `yaml:"type"`
	Source      string                `yaml:"source,omitempty"`
	Target      string                `yaml:"target"`
	ReadOnly    bool                  `yaml:"read_only,omitempty"`
	Consistency string                `yaml:"consistency,omitempty"`
	Bind        *composeBindOptions   `yaml:"bind,omitempty"`
	Volume      *composeVolumeOptions `yaml:"volume,omitempty"`
}

type composeBindOptions struct {
	Propagation string `yaml:"propagation,omitempty"`
	SELinux     string `yaml:"selinux,omitempty"`
}

type composeVolumeOptions struct {
	Subpath string `yaml:"subpath,omitempty"`
	NoCopy  bool   `yaml:"nocopy,omitempty"`
}

type composeTopVolume struct {
	Name string `yaml:"name"`
}

type composeSecret struct {
	File string `yaml:"file"`
}

type composeDeploy struct {
	Resources composeResources `yaml:"resources"`
}

type composeResources struct {
	Reservations composeReservations `yaml:"reservations"`
}

type composeReservations struct {
	Devices []composeDevice `yaml:"devices"`
}

type composeDevice struct {
	Driver       string   `yaml:"driver"`
	Count        any      `yaml:"count"` // "all" or a number
	Capabilities []string `yaml:"capabilities"`
}

// esc escapes `$` so compose does not interpolate already-resolved values.
func esc(s string) string { return strings.ReplaceAll(s, "$", "$$") }

func escSlice(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = esc(s)
	}
	return out
}

func escMap(in map[string]string) map[string]string {
	if len(in) == 0 {
		return nil
	}
	out := make(map[string]string, len(in))
	for k, v := range in {
		out[k] = esc(v)
	}
	return out
}
